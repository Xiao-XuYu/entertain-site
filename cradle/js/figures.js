/* 生成的闭环点列，所有花样点数、顺序完全一致，方便逐点插值变形 */
export function buildLoop(i) {
  const s = SHAPES[i];
  /* 两股绳都从手心高度离开手，再向两边散开花样；
     上下两股一前一后（z 分开），不会在手心里交叉成一团 */
  const wl = wrapPoints(-1, HAND_Y - 0.025, HAND_Y + 0.025);
  const wr = wrapPoints(1, HAND_Y + 0.025, HAND_Y - 0.025);
  const upA = new THREE.Vector3(-HX + 0.10, HAND_Y, 0.05);
  const upB = new THREE.Vector3(HX - 0.10, HAND_Y, 0.05);
  const loA = new THREE.Vector3(-HX + 0.10, HAND_Y, -0.05);
  const loB = new THREE.Vector3(HX - 0.10, HAND_Y, -0.05);
  const upCtrl = [wl[wl.length - 1], upA, ...s.upper.map(p => new THREE.Vector3(...p)), upB, wr[0]];
  const loCtrl = [wr[wr.length - 1], loB, ...s.lower.map(p => new THREE.Vector3(...p)), loA, wl[0]];
  const up = strandPoints(upCtrl).map(v => v.clone());
  const lo = strandPoints(loCtrl).map(v => v.clone());
  return [...wl, ...up, ...wr, ...lo];
}

