function resample(poly) {
  const curve = new THREE.CatmullRomCurve3(
    poly.map((p) => new THREE.Vector3(p[0], p[1], p[2] * 2.0)),
    false, 'centripetal', 0.5,
  );
  return curve.getSpacedPoints(K_STRAND - 1).map((v) => v.clone());
}

/* 每个花样的上下两股，点数固定，供换花样时逐点插值 */
export const SHAPE_PTS = SHAPES.map((s) => ({
  upper: resample(s.upper),
  lower: resample(s.lower),
}));

/* 花样横向尺度：手放大后出绳点落在 ±1.05（花样坐标），
   0.70 的花样端点要拉开到同一个宽度，绳才不会在手腕前先折一下 */
export const X_FIG = 1.5;

/* 两股绳在世界空间的中间控制点（左→右 / 右→左） */
export function shapeWorld(i) {
  const s = SHAPE_PTS[i];
  return {
    upper: s.upper.map((p) => worldPt(p.x * X_FIG, p.y, p.z)),
    lower: s.lower.map((p) => worldPt(p.x * X_FIG, p.y, p.z)),
  };
}

