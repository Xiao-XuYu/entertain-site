export const HX = 0.88;
const HAND_Y = 0.49;          // 手心在花样坐标系里的高度（与 HOLD 一致）
const WRAP_RX = 0.10;         // 绕手一圈：x 方向略大于手掌半宽
const WRAP_RZ = 0.075;        // z 方向从掌心后面绕到指节前面
const N_WRAP = 13;
const N_STRAND = 60;

/* 绳在手里绕一圈：贴着掌心、从手背绕到指尖前，而不是挂成一个长圈 */
function wrapPoints(side, y0, y1) {
  const pts = [];
  for (let i = 0; i < N_WRAP; i++) {
    const u = i / (N_WRAP - 1);
    const phi = (90 + 360 * u) * Math.PI / 180;
    const x = side * HX + side * WRAP_RX * Math.cos(phi);
    const y = y0 + (y1 - y0) * u;
    const z = WRAP_RZ * Math.sin(phi);
    pts.push(new THREE.Vector3(x, y, z));
  }
  return pts;
}

function strandPoints(ctrl, n = N_STRAND) {
  const curve = new THREE.CatmullRomCurve3(ctrl, false, 'centripetal', 0.5);
  return curve.getSpacedPoints(n - 1);
}

